"""
Benchmark Leaderboard and Markdown Report Generator.
"""

from __future__ import annotations

import json
from pathlib import Path

from harness.eval.metrics import BenchmarkSummary


class LeaderboardReporter:
    """Formats benchmark results into publication-ready Markdown and JSON summaries."""

    @staticmethod
    def generate_markdown(summary: BenchmarkSummary, model_name: str = "Claude 3.7 Sonnet") -> str:
        status_emoji = "PASSED" if summary.failed_tasks == 0 else "PARTIAL"

        md = [
            "# NexusCUH Evaluation Benchmark Report",
            "",
            f"**Evaluation Status:** `{status_emoji}`  ",
            f"**Model Under Test:** `{model_name}`  ",
            f"**Overall Pass Rate:** `{summary.pass_rate_percentage:.1f}%` ({summary.successful_tasks}/{summary.total_tasks} tasks)  ",
            f"**Average Steps / Task:** `{summary.avg_steps:.1f}`  ",
            f"**Average Wall-clock Latency:** `{summary.avg_duration_seconds:.2f}s`  ",
            f"**Total Cost (USD):** `${summary.total_cost_usd:.4f}`  ",
            "",
            "## Detailed Task Breakdown",
            "",
            "| Task Name | Category | Status | Steps | Duration (s) | Cost ($) | Termination Reason |",
            "|:---|:---|:---:|:---:|:---:|:---:|:---|",
        ]

        for t in summary.tasks:
            badge = "PASS" if t.success else "FAIL"
            md.append(
                f"| `{t.task_name}` | {t.category} | **{badge}** | {t.steps} | {t.duration_seconds:.2f} | ${t.estimated_cost_usd:.4f} | {t.termination_reason} |"
            )

        md.extend([
            "",
            "## Engineering Insights",
            "- **Ground-Truth Verification:** Evaluated with multi-modal file hash, regex, and MCP AST state assertions.",
            "- **Deterministic Reset:** Pristine state restored prior to each task invocation.",
            "- **Context Efficiency:** Visual frame deduplication & token pruning active.",
            "",
            "---",
            "*Generated by Nexus Computer Use Harness (NexusCUH) v0.1.0*",
        ])

        return "\n".join(md)

    @staticmethod
    def save_report(summary: BenchmarkSummary, output_path: str, model_name: str = "Claude 3.7 Sonnet") -> None:
        p = Path(output_path)
        p.parent.mkdir(parents=True, exist_ok=True)

        if p.suffix.lower() == ".json":
            with open(p, "w", encoding="utf-8") as f:
                json.dump(summary.to_dict(), f, indent=2)
        else:
            md_content = LeaderboardReporter.generate_markdown(summary, model_name)
            with open(p, "w", encoding="utf-8") as f:
                f.write(md_content)
